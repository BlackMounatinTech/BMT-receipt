const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({Intl,Date});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../crm_static/business_hours.js'),'utf8'),context);
const {describe}=context.BMTBusinessHours;
const schedule={weekly:{'0':[[480,1020]],'1':[[480,720],[780,1020]],'5':[],'6':[]}};
const at=s=>new Date(s);
assert.equal(describe(schedule,'America/New_York',at('2026-11-23T14:00:00Z')).state,'open');
assert.equal(describe(schedule,'America/Los_Angeles',at('2026-11-23T14:00:00Z')).state,'closed');
assert.match(describe(schedule,'America/New_York',at('2026-11-23T22:00:00Z')).text,/Closed/);
assert.equal(describe(schedule,'America/New_York',at('2026-11-24T17:30:00Z')).state,'closed');
assert.equal(describe(schedule,'America/New_York',at('2026-11-24T18:00:00Z')).state,'open');
assert.equal(describe(schedule,'America/New_York',at('2026-11-28T15:00:00Z')).today,'Today: Closed');
assert.equal(describe(schedule,'America/New_York',at('2026-11-25T15:00:00Z')).state,'unknown');
const overnight={weekly:{'0':[[1320,120]],'1':[]}};
assert.equal(describe(overnight,'America/New_York',at('2026-11-24T06:00:00Z')).state,'open');
assert.equal(describe(overnight,'America/New_York',at('2026-11-24T07:00:00Z')).state,'closed');
assert.equal(describe({weekly:{'0':[[0,1440]]}},'America/New_York',at('2026-11-24T04:59:00Z')).state,'open');
assert.equal(describe('{}','America/New_York').state,'unknown');
assert.equal(describe('invalid','America/New_York').state,'unknown');
console.log('Business hours: local time, closing boundary, split shifts, weekends, unknown days and overnight periods passed.');
